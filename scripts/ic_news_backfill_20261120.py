def records():
    for key, published, source, author, kind, title, url, summary, note in NEWS:
        event_date_only = key == 'micron-summit'
        yield {
            'id': key, 'content_type': 'news', 'source': source, 'title': title,
            'url': url, 'published_at': None if event_date_only else published,
            'date_kind': 'unknown' if event_date_only else 'news_published',
            'summary': summary, 'summary_kind': 'human',
            'news_genre': kind, 'news_scope': 'main',
            'verification_mode': 'original_page_review',
            'verification_note': f'署名或发布方：{author}。{note}',
        }


def import_news(database=DATABASE):
    return upsert_items(list(records()), origin='collected', db_path=database)


